export const products = [...baseProducts, ...extraProducts]

// Helper: get products sorted by year and month
export const getSortedProducts = () => {
  return [...products].sort((a, b) => {
    if (a.year !== b.year) return a.year - b.year
    return a.month - b.month
  })
}

// Helper: get products by category
export const getProductsByCategory = (category) => {
  if (category === 'all') return getSortedProducts()
  return getSortedProducts().filter((p) => p.category === category)
}

// Helper: get products by decade
export const getProductsByDecade = (decade) => {
  return getSortedProducts().filter((p) => Math.floor(p.year / 10) * 10 === decade)
}

// Get all decades
export const getDecades = () => {
  const decades = new Set()
  products.forEach((p) => decades.add(Math.floor(p.year / 10) * 10))
  return Array.from(decades).sort((a, b) => a - b)
}

